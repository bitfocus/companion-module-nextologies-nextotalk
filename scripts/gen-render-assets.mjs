// Bakes the key renderer's binary assets into src/generated/render-assets.ts as base64.
//
// The module draws the room name into the button image itself (see src/key-art.ts), using the
// resvg WebAssembly renderer and a bundled bold font. Both are embedded rather than read from
// disk at runtime because the dev build (dist/main.js) and the packaged build (pkg/main.js,
// webpack-bundled, no node_modules) would otherwise need different file paths.
// Runs as part of `yarn build` / `yarn dev`; re-run by hand with `node scripts/gen-render-assets.mjs`.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = dirname(dirname(fileURLToPath(import.meta.url)))
const require = createRequire(import.meta.url)

const wasm = readFileSync(require.resolve('@resvg/resvg-wasm/index_bg.wasm')).toString('base64')
const font = readFileSync(join(root, 'assets', 'fonts', 'Arimo-Bold.ttf')).toString('base64')

const out = `// GENERATED by scripts/gen-render-assets.mjs — do not edit.
// Arimo Bold: SIL Open Font License 1.1, see assets/fonts/OFL.txt.
export const RESVG_WASM_BASE64 = '${wasm}'
export const ROOM_NAME_FONT_BASE64 = '${font}'
`

const dest = join(root, 'src', 'generated', 'render-assets.ts')
mkdirSync(dirname(dest), { recursive: true })
writeFileSync(dest, out)
console.log(`wrote ${dest}`)
